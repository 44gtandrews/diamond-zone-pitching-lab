/* Reusable admin training-day/calendar regression smoke tests. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const h=require('../at-home-plan.js');
assert.equal(h.monday('2026-10-27'),'2026-10-26');
assert.equal(h.monday('2026-11-01'),'2026-10-26');
assert.equal(h.shiftWeek('2026-12-28',1),'2027-01-04');
assert.equal(h.shiftWeek('2027-01-04',-1),'2026-12-28');
assert.throws(()=>h.monday('2027-02-29'));
assert.deepEqual(h.weekDates('2026-10-26'),['2026-10-26','2026-10-27','2026-10-28','2026-10-29','2026-10-30','2026-10-31','2026-11-01']);
assert.equal(h.validResource(''),true);
assert.equal(h.validResource('https://drive.google.com/file/d/a/view'),true);
assert.equal(h.validResource('http://example.com'),false);
assert.equal(h.validResource('javascript:alert(1)'),false);
const template=h.cleanTemplate({id:'day-1',name:'Throw Day 1',color:'#50A3F8',rows:[{category:'Throwing',exercise:'Catch Play',notes:'45 throws',resource:''}]});
assert.equal(template.name,'Throw Day 1');
assert.equal(template.rows[0].exercise,'Catch Play');
assert.equal(template.rows[0].notes,'45 throws');
assert.equal('prescription' in template.rows[0],false);
const schedule=h.cleanSchedule([['day-1'],[],['day-1','day-2']]);
assert.equal(schedule.length,7);
assert.deepEqual(schedule[0],['day-1']);
assert.deepEqual(schedule[2],['day-1','day-2']);
const legacy=h.legacyToDraft([{day:'Monday',category:'Throwing',exercise:'Catch Play',prescription:'45 throws',notes:'easy effort',resource:''},{day:'Wednesday',category:'Strength',exercise:'Split squat',prescription:'3x8'}],'2026-10-26');
assert.equal(legacy.templates.length,2);
assert.equal(legacy.templates[0].rows[0].notes,'Prescription: 45 throws · easy effort');
assert.deepEqual(legacy.schedule[0],['legacy-2026-10-26-0']);
assert.deepEqual(legacy.schedule[2],['legacy-2026-10-26-2']);

const html=fs.readFileSync('index.html','utf8');
const rules=fs.readFileSync('firestore.rules','utf8');
const build=fs.readFileSync('prepare-firebase-hosting.sh','utf8');
assert.match(html,/id="tab-at-home-btn"/);
assert.match(html,/id="dz-plan-calendar"/);
assert.match(html,/id="dz-day-list"/);
assert.match(html,/id="dz-day-editor"/);
assert.match(html,/id="dz-day-name"/);
assert.match(html,/id="dz-plan-save">Save<\/button>/);
assert.doesNotMatch(html.slice(html.indexOf('<!-- Administrator-only calendar'),html.indexOf('<script>\n// Storage is attached')),/<>Prescription<\/th>|<th>Prescription<\/th>/);
assert.match(html,/window\.DZ_AT_HOME_ON_PLAYER/);
assert.match(html,/src="\.\/at-home-plan\.js"/);
assert.match(build,/at-home-plan\.js/);

const weekly=rules.split('match /players/{playerId}/atHomePlans/{weekId}')[1].split('match /players/{playerId}/atHomeDays/{libraryId}')[0];
const library=rules.split('match /players/{playerId}/atHomeDays/{libraryId}')[1].split('match /playerCodes/{code}')[0];
assert.match(weekly,/allow get, list: if isAdmin\(\)/);
assert.match(weekly,/allow create: if validPlan\(\)/);
assert.match(weekly,/allow update: if validPlan\(\)/);
assert.match(weekly,/request\.resource\.data\.schedule\.size\(\) == 7/);
assert.doesNotMatch(weekly,/canViewAll\(|assignedParent\(|isPitchingCoach\(/);
assert.match(library,/allow get, list: if isAdmin\(\) && libraryId == 'library'/);
assert.match(library,/allow create: if validLibrary\(\)/);
assert.match(library,/allow update: if validLibrary\(\)/);
assert.doesNotMatch(library,/canViewAll\(|assignedParent\(|isPitchingCoach\(/);
console.log('Admin calendar/day-library smoke tests passed: dates, templates, assignments, legacy preservation, admin-only rules.');
