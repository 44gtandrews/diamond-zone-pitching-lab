/* Mechanical changes completion and Firestore compatibility smoke test. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const m=require('../mechanical-changes.js');

const old={positives:['Better arm action','Maintaining posture'],negatives:['More hip-shoulder separation','Stay closed longer']};
const converted=m.normalize(old);
assert.deepEqual(converted,{positives:old.positives,negatives:old.negatives,completed:[]});
assert.deepEqual(old,{positives:['Better arm action','Maintaining posture'],negatives:['More hip-shoulder separation','Stay closed longer']},'must not mutate original');
const date='2026-10-29T12:30:00.000Z';
const done=m.complete(old,'negatives',0,date);
assert.deepEqual(done.positives,old.positives);
assert.deepEqual(done.negatives,['Stay closed longer']);
assert.deepEqual(done.completed,[{text:'More hip-shoulder separation',from:'negatives',completedAt:date}]);
assert.equal(old.negatives.length,2,'original unchanged');
const again=m.complete(done,'positives',1,date);
assert.deepEqual(again.positives,['Better arm action']);
assert.equal(again.completed[1].text,'Maintaining posture');
assert.equal(again.completed[1].from,'positives');
const reopened=m.reopen(again,0);
assert.deepEqual(reopened.negatives,['Stay closed longer','More hip-shoulder separation']);
assert.equal(reopened.completed.length,1);
assert.equal(reopened.completed[0].text,'Maintaining posture');
assert.deepEqual(m.reopen(reopened,0).positives,['Better arm action','Maintaining posture']);
assert.deepEqual(m.complete(old,'negatives',-1,date),m.normalize(old));
assert.deepEqual(m.complete(old,'invalid',0,date),m.normalize(old));
assert.deepEqual(m.reopen(old,10),m.normalize(old));
assert.deepEqual(m.complete({positives:[''],negatives:['  ']},'negatives',0,date).completed,[]);
const legacyCompleted=m.normalize({positives:['x'],negatives:[],completed:['Old adjustment']});
assert.deepEqual(legacyCompleted.completed,[{text:'Old adjustment',from:'negatives',completedAt:null}]);
assert.equal(m.normalize(null).completed.length,0);
assert.equal(m.normalize({positives:[1,'x'],negatives:'bad',completed:[null,{text:'done',from:'invalid',completedAt:4}]}).completed[0].from,'negatives');
const serialized=JSON.parse(JSON.stringify(done));
assert.deepEqual(m.normalize(serialized),done,'JSON round trip preserves completed changes and sources');

const html=fs.readFileSync('index.html','utf8');
const stage=fs.readFileSync('prepare-firebase-hosting.sh','utf8');
const workflow=fs.readFileSync('.github/workflows/deploy-firebase.yml','utf8');
const cloud=fs.readFileSync('cloud.js','utf8');
const rules=fs.readFileSync('firestore.rules','utf8');
assert.match(html,/id="mech-completed-list"/);
assert.match(html,/id="mech-pos-list"/);
assert.match(html,/id="mech-neg-list"/);
assert.match(html,/window\.DZ_CREATE_MECHANICAL_BOARD\(savedMech\)/);
assert.match(html,/const payload = player\._mechanicalBoard\.getValues\(\)/);
assert.match(html,/src="\.\/mechanical-changes\.js"/);
assert.ok(html.indexOf('src="./mechanical-changes.js"')<html.indexOf('src="./cloud.js"'));
assert.match(stage,/mechanical-changes\.js/);
assert.match(workflow,/node tests\/mechanical-changes-smoke\.test\.js/);
assert.match(cloud,/window\.DZ_EDIT_ENABLED=window\.DZ_IS_ADMIN\|\|staff\.role==='pitching_coach'/);
assert.match(cloud,/if\(!window\.DZ_AUTHORIZED \|\| !window\.DZ_EDIT_ENABLED\)/);
assert.match(rules,/match \/playerEdits\/\{playerId\}\/sections\/\{section\}/);
assert.match(rules,/section in \['notes', 'mechanics', 'strength'/);

console.log('Mechanical changes completion smoke tests passed: legacy notes, completion/reopen, storage and role wiring.');
