'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const html=fs.readFileSync('index.html','utf8'),importer=fs.readFileSync('importer.js','utf8'),cloud=fs.readFileSync('cloud.js','utf8'),session=fs.readFileSync('session-ui.js','utf8');
const start=html.indexOf('function dzNoTrackman('),end=html.indexOf('function getTypeSummary(',start);
assert.ok(start>=0&&end>start);
const noTrackman=new Function(html.slice(start,end)+';return dzNoTrackman;')();
const manual={id:'p-example',name:'Sample Player',ageNum:14,ageLabel:'14U',sessions:0,dataType:'aggregate',pitches:[]};
assert.equal(noTrackman(manual),true);
assert.equal(noTrackman({...manual,sessions:1}),false);
assert.equal(noTrackman({...manual,pitches:[{key:'fb'}]}),false);
assert.equal(noTrackman({...manual,dataType:'raw'}),false);
assert.equal(noTrackman(null),false);
const vStart=cloud.indexOf('  function validPlayer('),vEnd=cloud.indexOf("  $('cloud-import').addEventListener",vStart);
assert.ok(vStart>=0&&vEnd>vStart);
const validate=new Function('dzNoTrackman',cloud.slice(vStart,vEnd)+';return validPlayer;')(noTrackman);
assert.doesNotThrow(()=>validate(manual));
assert.throws(()=>validate({...manual,sessions:1}));
assert.throws(()=>validate({...manual,dataType:'raw',rawPitches:[{}]}));
assert.throws(()=>validate({...manual,sessions:-1}));
assert.doesNotThrow(()=>validate({...manual,sessions:1,pitches:[{key:'fb'}]}));
assert.ok(html.includes('id="session-create-manual"'));
assert.ok(html.includes('N/A — no TrackMan report uploaded'));
assert.ok(html.includes("['velo-stats','chart-move','chart-usage','pitch-table']"));
assert.ok(importer.includes("!window.DZ_AUTHORIZED||!window.DZ_IS_ADMIN"));
assert.ok(importer.includes('sessions:0,dataType:'));
assert.ok(importer.includes('pitches:[],createdBy:'));
assert.ok(importer.includes("if(!baselineSnap.exists&&!firstImport)"));
assert.ok(importer.includes('if(firstImport){'));
assert.ok(importer.includes('const firstImport=dzNoTrackman(old)'));
assert.ok(importer.includes('sessions:1,summaryOnly:'));
assert.ok(session.includes('if(dzNoTrackman(player))'));
console.log('Manual player smoke tests passed: empty profiles, backup validation, N/A views, admin role and first import wiring.');
