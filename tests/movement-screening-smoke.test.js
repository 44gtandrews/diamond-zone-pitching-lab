'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const m=require('../movement-screening.js');
assert.deepEqual(m.GROUPS.map(g=>g.name),['Shoulder','T-Spine','Hips']);
assert.equal(m.ROW_COUNT,9);
assert.equal(m.TEMPLATE_ID,'example-v1');
for(const role of ['admin','pitching_coach'])assert.equal(m.allowedRole(role),true);
for(const role of ['coach','player_parent',null,'unapproved'])assert.equal(m.allowedRole(role),false);
assert.equal(m.validDate('2026-02-30'),false);
assert.equal(m.validDate('2026-11-24'),true);
assert.deepEqual(m.blank('2026-11-24').scores,Array(9).fill(null));
assert.equal(m.validScores([2,1,0,null,'P',2,0,1,2]),true);
assert.equal(m.validScores([2,1,0,null,'P',2,0,1,3]),false);
assert.equal(m.validScores(Array(9).fill('2')),false);
const scores=[2,1,2,1,1,0,1,2,1];
assert.deepEqual(m.totals(scores,0,3),{points:5,max:6,scored:3,count:3,pain:0,complete:true});
assert.equal(m.totals(scores,3,3).points,2);
assert.equal(m.totals(scores,6,3).points,4);
assert.deepEqual(m.totals(scores,0,9),{points:11,max:18,scored:9,count:9,pain:0,complete:true});
assert.deepEqual(m.totals([2,null,'P'],0,3),{points:2,max:6,scored:1,count:3,pain:1,complete:false});
assert.deepEqual(m.totals([0,0,0],0,3),{points:0,max:6,scored:3,count:3,pain:0,complete:true});
assert.equal(m.validRecord({...m.blank('2026-11-24'),revision:1},'2026-11-24'),true);
assert.equal(m.validRecord({...m.blank('2026-11-24'),revision:1},'2026-11-25'),false);
const html=fs.readFileSync('index.html','utf8'),cloud=fs.readFileSync('cloud.js','utf8'),script=fs.readFileSync('movement-screening.js','utf8');
assert.match(html,/id="panel-strength"[\s\S]*?id="dz-screening" hidden/);
assert.match(html,/body:not\(\[data-dz-role="admin"\]\):not\(\[data-dz-role="pitching_coach"\]\) #dz-screening/);
assert.ok(html.includes("if(btn.dataset.tab==='strength')window.DZ_SCREENING_OPEN?.(currentPlayerId)"));
assert.ok(html.includes('window.DZ_SCREENING_ON_PLAYER?.(player)'));
assert.ok(cloud.includes('window.DZ_SCREENING_RESET?.()'));
assert.ok(cloud.includes('payload.collections.playerMovementScreens'));
assert.ok(cloud.includes('decoded.playerMovementScreens'));
assert.ok(!script.includes('.innerHTML'));
assert.ok(script.includes('window.DZ_AUTHORIZED===true&&allowedRole(window.DZ_ROLE)'));
assert.ok(script.includes('if(!permitted()||!id){reset();return;}'));
assert.ok(script.includes('if(!current(id,gen))return'));
console.log('Movement screening tests passed: scores, body-area totals, missing and pain handling, private UI, backup and stale-load guards.');
