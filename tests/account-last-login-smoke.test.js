/* Admin last-login feature and tamper-resistant Firestore auth_time rules. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const cloud=fs.readFileSync('cloud.js','utf8');
const html=fs.readFileSync('index.html','utf8');
const rules=fs.readFileSync('firestore.rules','utf8');
const workflow=fs.readFileSync('.github/workflows/deploy-firebase.yml','utf8');
const loginRules=rules.split('match /userLogins/{email} {')[1]?.split('match /coachRequests/{userId} {')[0];
assert.ok(loginRules,'Expected a dedicated userLogins collection');
assert.match(loginRules,/request\.auth\.token\.email\.lower\(\) == email/);
assert.match(loginRules,/return approved\(\)/);
assert.match(loginRules,/request\.resource\.data\.keys\(\)\.hasOnly\(/);
assert.match(loginRules,/\['email','uid','authTimeSeconds','recordedAt'\]/);
assert.match(loginRules,/request\.resource\.data\.uid == request\.auth\.uid/);
assert.match(loginRules,/request\.resource\.data\.authTimeSeconds is int/);
assert.match(loginRules,/request\.resource\.data\.authTimeSeconds == request\.auth\.token\.auth_time/);
assert.match(loginRules,/request\.resource\.data\.recordedAt == request\.time/);
assert.match(loginRules,/allow get: if isAdmin\(\) \|\| ownsLogin\(\)/);
assert.match(loginRules,/allow list: if isAdmin\(\)/);
assert.match(loginRules,/allow create: if validLogin\(\)/);
assert.match(loginRules,/allow update: if validLogin\(\)/);
assert.match(loginRules,/request\.resource\.data\.authTimeSeconds > resource\.data\.authTimeSeconds/);
assert.match(loginRules,/allow delete: if false/);
assert.doesNotMatch(loginRules,/allow list: if canViewAll\(\)/);

assert.match(cloud,/async function recordOwnLastSignIn\(user\)/);
assert.match(cloud,/const token=await user\.getIdTokenResult\(\)/);
assert.match(cloud,/Date\.parse\(token\.authTime\|\|''\)/);
assert.match(cloud,/Math\.floor\(Date\.parse\(token\.authTime\|\|''\)\/1000\)/);
assert.match(cloud,/db\.collection\('userLogins'\)\.doc\(emailKey\(user\.email\)\)/);
assert.match(cloud,/await db\.runTransaction\(async tx=>/);
assert.match(cloud,/if\(Number\.isSafeInteger\(previously\)&&previously>=signInSecs\)return/);
assert.match(cloud,/authTimeSeconds:signInSecs/);
assert.match(cloud,/firebase\.firestore\.FieldValue\.serverTimestamp\(\)/);
assert.match(cloud,/try\{await recordOwnLastSignIn\(activeUser\);\}/);
assert.match(cloud,/catch\(error\)\{console\.warn\('Last login timestamp could not be recorded'/);
assert.match(cloud,/db\.collection\('userLogins'\)\.get\(\)\.catch/);
assert.match(cloud,/const loginByEmail=new Map\(/);
assert.match(cloud,/loginByEmail\.get\(doc\.id\)\?\.authTimeSeconds/);
assert.match(cloud,/loginValue\.textContent=logins/);
assert.match(cloud,/:'Temporarily unavailable';/);
assert.match(cloud,/function formatLastSignIn\(authTimeSeconds\)/);
assert.match(cloud,/new Date\(authTimeSeconds\*1000\)/);
assert.match(cloud,/timeZone:'America\/New_York'/);
assert.match(cloud,/textContent='LAST LOGIN'/);
assert.match(cloud,/textContent=logins/);
assert.match(cloud,/return 'Not recorded yet'/);
assert.match(html,/\.dz-account-last-login/);
assert.match(html,/Last Login uses Firebase’s verified sign-in timestamp/);
assert.match(html,/Eastern time/);
assert.match(html,/id="cloud-allowlist"/);
assert.match(workflow,/node tests\/account-last-login-smoke\.test\.js/);
console.log('Admin last-login smoke checks passed: Firebase auth_time, own-only writes, admin-only listing, timezone, and fallback.');
